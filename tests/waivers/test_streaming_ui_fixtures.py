"""Weekly IDP Streaming — the UI's fixtures ARE the composer's output.

``frontend/__tests__/fixtures/idp-streaming/*.json`` are what the streaming
component tests and the E2E journey render.  They are generated by
:mod:`tests.waivers.streaming_ui_payloads` through the real
``assemble_streaming``; this test regenerates every scenario and requires byte
equality, so a payload-shape change fails here until the fixtures (and
therefore the frontend tests) are regenerated with it::

    python -m tests.waivers.streaming_ui_payloads
"""

from __future__ import annotations

import json

import pytest

from tests.waivers import streaming_ui_payloads as ui


@pytest.mark.parametrize("name", sorted(ui.SCENARIOS))
def test_committed_ui_fixture_matches_the_composer(name):
    path = ui.fixture_path(name)
    assert path.exists(), f"missing {path}; run python -m tests.waivers.streaming_ui_payloads"
    assert path.read_text(encoding="utf-8") == ui.serialize(ui.build(name)), (
        f"{path.name} is stale against the composer; regenerate with "
        "python -m tests.waivers.streaming_ui_payloads"
    )


def test_fixtures_cover_every_state_the_ui_renders():
    load = {n: json.loads(ui.fixture_path(n).read_text(encoding="utf-8")) for n in ui.SCENARIOS}
    rec = load["recommend"]
    assert rec["recommendMove"] is True and len(rec["plan"]["adds"]) == 2
    assert rec["plan"]["dynastyValueChange"]["state"] == "partial_unknown_add_values"
    assert rec["alternatives"], "the UI compares individual and multiple transactions"
    assert len(rec["weeks"]) == 2 and len(rec["plan"]["gainByWeekPoints"]) == 2
    assert rec["unprojectedRosterPlayers"]
    assert {r["dropClass"] for r in rec["safeToDrop"]["players"]} == {
        "churn",
        "conditional",
        "protected",
    }
    assert {r["bidBasis"] for r in rec["streamingBoard"]} >= {
        "faab_engine",
        "off_board_zero_claim_only",
    }
    limited = load["budget-limited"]
    assert limited["recommendMove"] is True and len(limited["plan"]["adds"]) == 1
    assert limited["largerBudget"]["plan"] is not None
    assert load["no-move"]["recommendMove"] is False and load["no-move"]["noMoveReason"]
    assert load["bounded"]["solver"]["status"] == "bounded"
    assert load["bounded"]["solver"]["boundGap"] is not None
