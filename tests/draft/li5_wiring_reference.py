def _pid(name: str) -> str:
    return name.lower().replace(" ", "_")


def _row(name: str, value: float | None, pos: str, sources: int, rookie: bool) -> dict[str, Any]:
    row: dict[str, Any] = {
        "playerId": _pid(name),
        "displayName": name,
        "canonicalName": name,
        "legacyRef": name,
        "assetClass": "idp" if pos in ("DL", "LB", "DB") else "offense",
        "position": pos,
        "pos": pos,
        "fantasyPositions": [pos],
        "team": "FA",
        "sourceCount": sources,
        "rookie": rookie,
    }
    if value is not None:
        row["rankDerivedValue"] = value
        row["values"] = {"full": value}
    return row


