"""Flag ``forced_drop_cheapest_legal`` OFF is byte-identical to the incumbent.

``tests/fixtures/forced_drop_flag_off_reference.json`` was generated by
``tests/trade/forced_drop_reference.py`` on ``e1eff9f5f`` — the commit BEFORE the
forced-drop fix — and re-recorded on pure ``main@7f35463ef`` (no fix) after train 17
changed the War Room payload, over an adversarial synthetic league and every consumer the
fix reaches: the roster-capacity owner (``assess_roster_capacity`` /
``forced_drop_cost``, which Angle, Suggestions, Best Offers, Perfect Waivers and
the counterparty blocks read), ``/api/trade/simulate`` (Trade Calculator),
``/api/trade/analyze`` with Team Context (War Room) and the Trade Finder's
forced-drop re-rank.  With the flag OFF every one must reproduce it exactly.

With the flag ON the same corpus MUST differ (otherwise this test proves
nothing about the switch).
"""

from __future__ import annotations

import json

import pytest

from src.api import feature_flags
from tests.trade import forced_drop_reference as R

ENV = "RISKIT_FEATURE_FORCED_DROP_CHEAPEST_LEGAL"


@pytest.fixture(scope="module")
def reference():
    return json.loads(R.OUT.read_text(encoding="utf-8"))


def _built(monkeypatch, value):
    if value is None:
        monkeypatch.delenv(ENV, raising=False)
    else:
        monkeypatch.setenv(ENV, value)
    feature_flags.reload()
    try:
        return R.reference()
    finally:
        monkeypatch.delenv(ENV, raising=False)
        feature_flags.reload()


@pytest.mark.parametrize("value", [None, "0"], ids=["default", "explicit_off"])
def test_flag_off_reproduces_the_pre_fix_reference(monkeypatch, reference, value):
    now = _built(monkeypatch, value)
    assert set(now["digests"]) == set(reference["digests"])
    for key, digest in reference["digests"].items():
        assert now["digests"][key] == digest, f"{key} changed with the flag OFF"
    for key, block in reference["capacity"].items():
        assert now["capacity"][key] == block, f"capacity {key} changed with the flag OFF"
    assert R.canonical(now) == R.canonical(reference)


def test_flag_on_changes_the_corpus(monkeypatch, reference):
    now = _built(monkeypatch, "1")
    changed = [k for k, d in reference["digests"].items() if now["digests"][k] != d]
    assert any(k.startswith("simulate/") for k in changed)
    assert any(k.startswith("analyze/") for k in changed)
    assert any(k.startswith("finder/") for k in changed)
