def _pid(name: str) -> str:
    return name.lower().replace(" ", "_")


def _row(name: str, value: float | None, pos: str) -> dict[str, Any]:
    row: dict[str, Any] = {
        "playerId": _pid(name),
        "displayName": name,
        "canonicalName": name,
        "legacyRef": name,
        "assetClass": "idp" if pos in ("DL", "LB", "DB") else "offense",
        "position": pos,
        "pos": pos,
        "fantasyPositions": [pos],
        "team": "FA",
    }
    if value is not None:
        row["rankDerivedValue"] = value
        row["values"] = {"full": value}
    return row


def contract(*, extra_us: tuple = (), drop_us: tuple = ()) -> dict[str, Any]:
    rows = [_row(n, v, p) for n, v, p in (*US, *THEM, *FREE_AGENTS, *extra_us)]
    rows.append(
        {
            "displayName": PICK[0],
            "canonicalName": PICK[0],
            "assetClass": "pick",
            "pos": "PICK",
            "position": "PICK",
            "rankDerivedValue": PICK[1],
            "values": {"full": PICK[1]},
        }
    )
    us_names = [n for n, _v, _p in (*US, *extra_us) if n not in drop_us] + [GHOST]
    us = {
        "ownerId": "o1",
        "name": "Us",
        "roster_id": 1,
        "players": us_names,
        "playerIds": [_pid(n) for n in us_names],
        "picks": [PICK[0]],
    }
    them = {
        "ownerId": "o2",
        "name": "Them",
        "roster_id": 2,
        "players": [n for n, _v, _p in THEM],
        "playerIds": [_pid(n) for n, _v, _p in THEM],
        "picks": [],
    }
    return {
        "meta": {"leagueKey": "fd_test"},
        "playersArray": rows,
        "sleeper": {
            "teams": [us, them],
            "rosterPositions": [
                *(slot for slot, n in STARTERS.items() for _ in range(n)),
                *(["BN"] * (ROSTER_SIZE - sum(STARTERS.values()))),
            ],
        },
    }


