#: league variant -> (roster settings, contract kwargs)
LEAGUES: dict[str, tuple[dict[str, Any] | None, dict[str, Any]]] = {
    "capped": (SETTINGS, {}),
    "over_before": (SETTINGS, {"extra_us": (("WR Extra", 500.0, "WR"),)}),
    "taxi_unknown": ({**SETTINGS, "taxiSize": 2}, {}),
    "unknown_cap": ({k: v for k, v in SETTINGS.items() if k != "rosterSize"}, {}),
}


#: The finder arbitrages our board against the retail market, so the market
#: must disagree with the board for any trade to qualify: their players are
#: priced 15% under our board by the "market", ours 10% over.
_THEIR_NAMES = {n for n, _v, _p in THEM}


def _finder_players(c: dict[str, Any]) -> dict[str, Any]:
    out: dict[str, Any] = {}
    for row in c["playersArray"]:
        if row.get("assetClass") == "pick" or "rankDerivedValue" not in row:
            continue
        v = row["rankDerivedValue"]
        market = round(v * (0.85 if row["displayName"] in _THEIR_NAMES else 1.10))
        out[row["displayName"]] = {
            "position": row["position"],
            "team": "FA",
            "_finalAdjusted": v,
            "_sites": 4,
            "_canonicalSiteValues": {"ktcSfTep": market},
        }
    return out


def build() -> dict[str, Any]:
    out: dict[str, Any] = {"capacity": {}, "simulate": {}, "analyze": {}, "finder": {}}
    for league, (settings, kw) in LEAGUES.items():
        c = contract(**kw)
        us = terminal.resolve_team(c, owner_id="o1", name=None)
        ctx = RC.build_capacity_context(c, None, us, roster_settings=settings)
        for trade, (pin, pout, _kin, _kout) in TRADES.items():
            cap = RC.assess_roster_capacity(ctx, incoming_players=pin, outgoing_players=pout)
            cost, basis = RC.forced_drop_cost(cap)
            out["capacity"][f"{league}/{trade}"] = {
                "capacity": cap.to_dict(),
                "forcedDropCost": cost,
                "forcedDropCostBasis": basis,
            }
            if league in ("capped", "over_before"):
                sim = trade_simulator.simulate_trade(
                    copy.deepcopy(c),
                    resolved_team=us,
                    players_in=list(pin),
                    players_out=list(pout),
                    picks_in=list(_kin),
                    picks_out=list(_kout),
                    roster_settings=settings,
                    league_key=None,
                )
                out["simulate"][f"{league}/{trade}"] = sim
                sim_tc = copy.deepcopy(sim)
                sim_tc["teamContext"] = {"applied": True, "mode": "team"}
                out["analyze"][f"{league}/{trade}"] = analyze_trade(sim_tc, counterfactuals=True)
        if league in ("capped", "over_before"):
            res = find_trades(
                players=_finder_players(c),
                my_team="Us",
                opponent_teams=["Them"],
                sleeper_teams=c["sleeper"]["teams"],
                contract=c,
                capacity_context=ctx,
                use_team_context=True,
            )
            out["finder"][league] = res
    return out


def canonical(obj: Any) -> str:
    return json.dumps(obj, sort_keys=True, indent=1, default=str) + "\n"


def reference(built: dict[str, Any] | None = None) -> dict[str, Any]:
    """The committed form: the capacity blocks in full (small, and the part a
    reviewer wants to read), and a sha256 of every whole simulate / analyze /
    finder payload (about 1 MB verbatim) — byte identity is what is asserted,
    and a digest asserts exactly that."""
    built = build() if built is None else built
    digests = {
        f"{section}/{key}": hashlib.sha256(canonical(payload).encode("utf-8")).hexdigest()
        for section in ("simulate", "analyze", "finder")
        for key, payload in sorted(built[section].items())
    }
    return {"capacity": built["capacity"], "digests": digests}


def main() -> int:
    OUT.write_text(canonical(reference()), encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
