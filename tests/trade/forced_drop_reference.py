"""Forced-drop fix: the flag-OFF reference corpus.

``forced_drop_cheapest_legal`` (``src/trade/forced_drop_selection.py``) changes
which player a full roster releases and what that release is charged.  It ships
default OFF, and with the flag OFF every served output must be byte-identical to
the code BEFORE the fix.  This module builds a deterministic synthetic league and
runs every forced-drop consumer the fix reaches:

* ``roster_capacity.assess_roster_capacity(...).to_dict()`` and
  ``forced_drop_cost`` (the canonical owner; Angle, Suggestions, Best Offers,
  Perfect Waivers and the counterparty blocks read exactly these);
* ``trade_simulator.simulate_trade`` (``/api/trade/simulate``, the Trade
  Calculator) — the whole response;
* ``analyze_trade.analyze_trade`` with Team Context ON (``/api/trade/analyze``,
  the War Room) — the whole packet;
* ``finder.find_trades`` with Team Context ON and a capacity context (the Trade
  Finder's ``forced_drop_cost`` re-rank) — the whole result.

``tests/fixtures/forced_drop_flag_off_reference.json`` (the capacity blocks in
full, a sha256 of every other payload) was generated by this module on the
commit BEFORE the fix (``e1eff9f5f``) and re-recorded on ``main@7f35463ef`` (pure
main, without this fix) when train 17 changed the War Room payload, and
``test_forced_drop_flag_off_identity.py`` requires the flag-OFF output to match it
byte for byte.  Regenerate only if a DIFFERENT, deliberate change moves these
surfaces::

    python -m tests.trade.forced_drop_reference

The league is deliberately adversarial for the defect: a capped roster whose
sub-waiver players' names sort in the OPPOSITE order to their values (so the
retired ``(ECC, name)`` order and the cheapest-legal order disagree), an unpriced
board row, a name that joins to no board row, and incoming fillers cheaper than
every rostered player.
"""

