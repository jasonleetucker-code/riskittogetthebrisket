// Generates tests/fixtures/package_model_float_cases.json from the JS owner
// (frontend/lib/trade-logic.js::geomPackageUtility / packageAdjustPair).
//
// The fixture pins BIT-identical geometric package utilities across the two
// languages: each `utility` is the shortest round-trip decimal of the JS
// double, which Python's float() and JS Number() both parse back to the
// exact same bits.  Asserted by tests/valuation_math/test_package_model_float.py
// and frontend/__tests__/package-model.test.js.
//
//   node frontend/scripts/generate-package-model-float-cases.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { geomPackageUtility, packageAdjustPair } from "../lib/trade-logic.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "../../tests/fixtures/package_model_float_cases.json");

// Deterministic LCG — no Math.random, so the fixture regenerates identically.
let seed = 20261019;
const rnd = () => (seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648;
const side = (max) =>
  Array.from({ length: 1 + Math.floor(rnd() * max) }, () => Math.floor(rnd() * 9999) + 1);

const cases = [];
for (let k = 0; k < 240; k += 1) {
  // Deep packages on purpose: `q ** i` diverged between V8 and CPython from i = 4.
  const team1 = side(k < 120 ? 12 : 4);
  const team2 = side(k < 120 ? 4 : 12);
  const r = packageAdjustPair(team1, team2, { modelId: "geom_q078_v1" });
  cases.push({
    team1,
    team2,
    utility1: String(geomPackageUtility(team1)),
    utility2: String(geomPackageUtility(team2)),
    expected: [r.value, r.side, r.displayed],
  });
}
const payload = {
  _comment:
    "Bit-identical geometric package utility (geom_q078_v1) across JS and Python: " +
    "iterative weights (w *= q) and a left fold in both owners, never ** / Math.pow / " +
    "compensated sum(). Generated by frontend/scripts/generate-package-model-float-cases.mjs; " +
    "asserted by tests/valuation_math/test_package_model_float.py and " +
    "frontend/__tests__/package-model.test.js. Regenerate only when the math deliberately changes.",
  q: 0.78,
  cases,
};
writeFileSync(out, `${JSON.stringify(payload, null, 1)}\n`);
console.log(`wrote ${cases.length} cases to ${out}`);
