async def amain(h: Harness) -> tuple[dict, dict, dict]:
    contract = h.prepare_contract()
    h.start_server(contract)
    print(f"[setup] server pid={h.proc.pid} {h.base} store={h.db_path}")
    await h.wait_ready()
    stop = asyncio.Event()
    base_task = asyncio.create_task(h.health_loop(h.health_baseline, stop))
    await asyncio.sleep(3.0)
    stop.set()
    await base_task
    await h.setup()
    print(
        f"[setup] room {h.room}: 12 human seats, {len(h.pool_ids)} pool players, 12 lots open; "
        f"load for {h.a.duration:.0f}s ..."
    )
    await h.run_load()
    await h.verify_http()
    prop = h.propagation()
    return prop, {}, {}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="12-manager load rehearsal for the rookie auction room (LOCAL ONLY).",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    ap.add_argument("--duration", type=float, default=120.0, help="load phase seconds")
    ap.add_argument("--seed", type=int, default=20260929)
    ap.add_argument("--tabs-min", type=int, default=2)
    ap.add_argument("--tabs-max", type=int, default=3)
    ap.add_argument("--bidders-per-manager", type=int, default=2)
    ap.add_argument(
        "--bid-interval", type=float, default=0.8, help="mean seconds between commands per bidder"
    )
    ap.add_argument(
        "--burst-every", type=float, default=20.0, help="seconds between bursts (0 = none)"
    )
    ap.add_argument("--burst-seconds", type=float, default=4.0)
    ap.add_argument(
        "--burst-interval",
        type=float,
        default=0.05,
        help="mean seconds between commands in a burst",
    )
    ap.add_argument(
        "--replay-rate",
        type=float,
        default=0.05,
        help="share of accepted commands resent with the same key",
    )
    ap.add_argument(
        "--conflict-rate",
        type=float,
        default=0.01,
        help="share resent with the same key but a different body",
    )
    ap.add_argument("--advice-interval", type=float, default=15.0)
    ap.add_argument("--notify-interval", type=float, default=10.0)
    ap.add_argument("--health-interval", type=float, default=0.1)
    ap.add_argument("--reconnect-every", type=float, default=5.0)
    ap.add_argument(
        "--clock-jump-every", type=float, default=20.0, help="0 disables mock clock jumps"
    )
    ap.add_argument("--clock-jump-seconds", type=float, default=30.0)
    ap.add_argument("--lot-seconds", type=int, default=60, help="auction_active_seconds (min 60)")
    ap.add_argument("--extension-seconds", type=int, default=15)
    ap.add_argument("--poll-wait", type=float, default=25.0)
    ap.add_argument("--drain-seconds", type=float, default=10.0)
    ap.add_argument("--budgets", default="", help="12 comma-separated opening budgets")
    ap.add_argument("--contract", choices=["auto", "export", "synthetic"], default="auto")
    ap.add_argument("--export-path", default="")
    ap.add_argument("--port", type=int, default=0, help="0 = ephemeral")
    ap.add_argument("--startup-timeout", type=float, default=240.0)
    ap.add_argument(
        "--server-log-level", default="info", help="uvicorn log level (production uses info)"
    )
    ap.add_argument("--target-bid-p95", type=float, default=1.0)
    ap.add_argument("--target-visible-p95", type=float, default=2.0)
    ap.add_argument(
        "--strict-targets", action="store_true", help="exit 3 when a latency target is missed"
    )
    ap.add_argument("--json-out", default="")
    ap.add_argument("--keep-tmp", action="store_true")
    args = ap.parse_args(argv)
    if not (1 <= args.tabs_min <= args.tabs_max):
        ap.error("need 1 <= --tabs-min <= --tabs-max")

    h = Harness(args)
    code = EXIT_OK
    out: dict = {}
    try:
        try:
            prop, _, _ = asyncio.run(amain(h))
        except Exception as exc:  # noqa: BLE001
            print(f"[harness] setup/run failure: {type(exc).__name__}: {exc}", file=sys.stderr)
            h.kill_server()
            tail = (
                h.log_path.read_text(encoding="utf-8", errors="replace")[-3000:]
                if h.log_path.exists()
                else ""
            )
            if tail:
                print("[server log tail]\n" + tail, file=sys.stderr)
            return EXIT_SETUP
        h.kill_server()
        db = h.verify_db()
        log_counts = h.scan_log()
        out = report(h, db, log_counts, prop)
        if h.violations:
            code = EXIT_INVARIANT
        elif args.strict_targets and not all(out["targets"].values()):
            code = EXIT_TARGET
        if args.json_out:
            Path(args.json_out).write_text(json.dumps(out, indent=2, default=str), encoding="utf-8")
            print(f"[report] JSON written to {args.json_out}")
    finally:
        if h.proc and h.proc.poll() is None:
            h.kill_server()
        if args.keep_tmp:
            print(f"[cleanup] kept temp dir {h.tmp}")
        else:
            import gc

            gc.collect()  # release any sqlite handles before removing the temp store
            shutil.rmtree(h.tmp, ignore_errors=True)
    return code


if __name__ == "__main__":
    raise SystemExit(main())
