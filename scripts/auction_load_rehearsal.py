_store_mod.Store.read = _timed_read


class _TimedLock:
    """Wraps the store's process-wide writer RLock to time contention."""

    def __init__(self, inner):
        self._inner = inner

    def acquire(self, *a, **k):
        t0 = time.perf_counter()
        ok = self._inner.acquire(*a, **k)
        _rec("writer_lock_wait", time.perf_counter() - t0)
        return ok

    def release(self):
        self._inner.release()

    def __enter__(self):
        self.acquire()
        return self

    def __exit__(self, *exc):
        self.release()
        return False


