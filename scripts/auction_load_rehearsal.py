    async def wait_ready(self) -> None:
        deadline = time.monotonic() + self.a.startup_timeout
        async with httpx.AsyncClient(base_url=self.base, verify=_SSL, timeout=5) as c:
            while time.monotonic() < deadline:
                if self.proc and self.proc.poll() is not None:
                    raise RuntimeError(f"server exited early (code {self.proc.returncode})")
                try:
                    r = await c.get("/api/_load/metrics")
                    if r.status_code == 200:
                        self.server_pid = int(r.json()["pid"])
                        return
                except httpx.HTTPError:
                    pass
                await asyncio.sleep(0.5)
        raise RuntimeError("server did not become ready in time")

    def kill_server(self) -> None:
        """Crash-style stop: acknowledged actions must survive a hard kill."""
        pids = [p for p in (self.server_pid, self.proc.pid if self.proc else None) if p]
        for pid in dict.fromkeys(pids):
            try:
                os.kill(pid, signal.SIGKILL if hasattr(signal, "SIGKILL") else signal.SIGTERM)
            except OSError:
                pass
        if self.proc:
            try:
                self.proc.wait(timeout=15)
            except subprocess.TimeoutExpired:
                self.proc.kill()
        if self.log_fh:
            self.log_fh.close()
            self.log_fh = None

