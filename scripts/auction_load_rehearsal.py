class ProcStats:
    def __init__(self, pid: int):
        self.pid = pid
        self.method = "unavailable"
        self.handle_label = "open FDs"
        self._p = None
        self._h = None
        if psutil is not None:
            try:
                self._p = psutil.Process(pid)
                self.method = "psutil"
                if os.name == "nt":
                    self.handle_label = "open handles (Windows handle count, not POSIX FDs)"
                return
            except Exception:  # noqa: BLE001
                self._p = None
        if sys.platform.startswith("linux") and Path(f"/proc/{pid}/stat").exists():
            self.method = "procfs"
            self._tck = os.sysconf("SC_CLK_TCK")
            return
        if os.name == "nt":
            try:
                import ctypes
                from ctypes import wintypes

                self._ct = ctypes
                self._wt = wintypes
                self._k32 = ctypes.WinDLL("kernel32", use_last_error=True)
                self._k32.OpenProcess.restype = wintypes.HANDLE
                h = self._k32.OpenProcess(0x1000, False, pid)  # QUERY_LIMITED_INFORMATION
                if h:
                    self._h = h
                    self.method = "win32-ctypes"
                    self.handle_label = "open handles (Windows handle count, not POSIX FDs)"
            except Exception:  # noqa: BLE001
                self._h = None

    def sample(self) -> dict | None:
        try:
            if self.method == "psutil":
                ct = self._p.cpu_times()
                out = {
                    "cpu_s": ct.user + ct.system,
                    "rss": self._p.memory_info().rss,
                    "threads": self._p.num_threads(),
                }
                try:
                    out["fds"] = self._p.num_fds() if os.name != "nt" else self._p.num_handles()
                except Exception:  # noqa: BLE001
                    out["fds"] = None
                return out
            if self.method == "procfs":
                with open(f"/proc/{self.pid}/stat", encoding="ascii") as fh:
                    parts = fh.read().rsplit(")", 1)[1].split()
                cpu = (int(parts[11]) + int(parts[12])) / self._tck
                threads = int(parts[17])
                rss = None
                with open(f"/proc/{self.pid}/status", encoding="ascii") as fh:
                    for line in fh:
                        if line.startswith("VmRSS:"):
                            rss = int(line.split()[1]) * 1024
                try:
                    fds = len(os.listdir(f"/proc/{self.pid}/fd"))
                except OSError:
                    fds = None
                return {"cpu_s": cpu, "rss": rss, "fds": fds, "threads": threads}
            if self.method == "win32-ctypes":
                ct, wt = self._ct, self._wt

                class FILETIME(ct.Structure):
                    _fields_ = [("lo", wt.DWORD), ("hi", wt.DWORD)]

                class PMC(ct.Structure):
                    _fields_ = [
                        ("cb", wt.DWORD),
                        ("PageFaultCount", wt.DWORD),
                        ("PeakWorkingSetSize", ct.c_size_t),
                        ("WorkingSetSize", ct.c_size_t),
                        ("QuotaPeakPagedPoolUsage", ct.c_size_t),
                        ("QuotaPagedPoolUsage", ct.c_size_t),
                        ("QuotaPeakNonPagedPoolUsage", ct.c_size_t),
                        ("QuotaNonPagedPoolUsage", ct.c_size_t),
                        ("PagefileUsage", ct.c_size_t),
                        ("PeakPagefileUsage", ct.c_size_t),
                    ]

                c, e, k, u = FILETIME(), FILETIME(), FILETIME(), FILETIME()
                if not self._k32.GetProcessTimes(
                    self._h, ct.byref(c), ct.byref(e), ct.byref(k), ct.byref(u)
                ):
                    return None
                cpu = (((k.hi << 32) | k.lo) + ((u.hi << 32) | u.lo)) / 1e7
                pmc = PMC()
                pmc.cb = ct.sizeof(PMC)
                rss = None
                if self._k32.K32GetProcessMemoryInfo(self._h, ct.byref(pmc), pmc.cb):
                    rss = int(pmc.WorkingSetSize)
                hc = wt.DWORD()
                fds = (
                    int(hc.value)
                    if self._k32.GetProcessHandleCount(self._h, ct.byref(hc))
                    else None
                )
                return {"cpu_s": cpu, "rss": rss, "fds": fds, "threads": None}
        except Exception:  # noqa: BLE001
            return None
        return None


