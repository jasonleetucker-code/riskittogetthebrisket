@contextmanager
def _timed_write(self):
    t0 = time.perf_counter()
    try:
        with _orig_write(self) as conn:
            t1 = time.perf_counter()
            _rec("write_acquire", t1 - t0)
            try:
                yield conn
            finally:
                t2 = time.perf_counter()
                _rec("write_hold", t2 - t1)
        _rec("write_commit", time.perf_counter() - t2)
    except sqlite3.Error as exc:
        _err("write", exc)
        raise


@contextmanager
def _timed_read(self):
    t0 = time.perf_counter()
    try:
        with _orig_read(self) as conn:
            _rec("read_open", time.perf_counter() - t0)
            yield conn
    except sqlite3.Error as exc:
        _err("read", exc)
        raise


