    # -- the run --------------------------------------------------------------------

    async def run_load(self) -> None:
        async with httpx.AsyncClient(base_url=self.base, verify=_SSL, timeout=10) as c:
            await c.post("/api/_load/reset")
        ps = ProcStats(self.server_pid or 0)
        self.proc_method = ps.method
        self.handle_label = ps.handle_label
        aux_stop = asyncio.Event()
        aux = [
            asyncio.create_task(self.health_loop(self.health, aux_stop)),
            asyncio.create_task(self.lag_loop(aux_stop)),
            asyncio.create_task(self.sampler(aux_stop, ps)),
        ]
        self.t_load0 = now()
        for m in self.managers:
            for tab in range(m.tab_count):
                m.tab_tasks[tab] = asyncio.create_task(self.tab_loop(m, tab))
        # Let every tab take its first snapshot before bidding.
        await asyncio.sleep(1.0)
        load = []
        for m in self.managers:
            for n in range(self.a.bidders_per_manager):
                load.append(asyncio.create_task(self.bidder(m, n)))
            load.append(asyncio.create_task(self.advice_loop(m)))
            load.append(asyncio.create_task(self.notify_loop(m)))
        load.append(asyncio.create_task(self.reconnect_loop()))
        load.append(asyncio.create_task(self.clock_loop()))
        await asyncio.sleep(self.a.duration)
        self.stop_load.set()
        self.t_load1 = now()
        print("[load] duration reached; stopping actors, draining in-flight commands ...")
        done, pending = await asyncio.wait(load, timeout=90)
        for t in pending:
            t.cancel()
        for t in done:
            if t.exception() is not None:
                self.notes.append(f"actor task error: {t.exception()!r}")
        # Drain: every tab should converge on the server's final revision.
        await self.drain()
        self.stop_polls.set()
        for m in self.managers:
            for t in m.tab_tasks.values():
                t.cancel()
            for t in m.tab_tasks.values():
                try:
                    await t
                except (asyncio.CancelledError, Exception):  # noqa: BLE001
                    pass
        async with httpx.AsyncClient(base_url=self.base, verify=_SSL, timeout=30) as c:
            self.server_metrics = (await c.get("/api/_load/metrics")).json()
        aux_stop.set()
        await asyncio.gather(*aux, return_exceptions=True)

    async def drain(self) -> None:
        c = self.client(self.managers[0].cookie)
        try:
            deadline = now() + self.a.drain_seconds
            final = None
            while now() < deadline:
                st, raw, _ = await self.call(
                    c, "GET", f"/api/auction/rooms/{self.room}/view", "final"
                )
                if st == 200:
                    final = int(json.loads(raw)["revision"])
                    lag = [
                        (m.idx, tab)
                        for m in self.managers
                        for tab in m.tab_tasks
                        if not self.obs[(m.idx, tab)] or self.obs[(m.idx, tab)][-1][1] < final
                    ]
                    if not lag:
                        break
                await asyncio.sleep(0.25)
            self.final_revision = final
            self.tabs_behind_at_end = []
            if final is not None:
                for m in self.managers:
                    for tab in m.tab_tasks:
                        o = self.obs[(m.idx, tab)]
                        last = o[-1][1] if o else -1
                        if last < final:
                            self.tabs_behind_at_end.append((m.seat, tab, last, final))
        finally:
            await c.aclose()

    # -- verification -----------------------------------------------------------------

    async def verify_http(self) -> None:
        """Fresh read of every seat's view + every acknowledged receipt."""
        oc = self.client(self.managers[0].cookie)
        try:
            r = await oc.get(f"/api/auction/rooms/{self.room}/view")
            view = r.json()
        finally:
            await oc.aclose()
        pub = view["public"]
        self.final_public = pub
        for s in pub["seats"]:
            bal, com, sp = s["balance"], s["committed"], s["spendable"]
            if bal is None:
                continue
            if bal < 0 or com > bal or sp < 0:
                self.violations.append(
                    f"HTTP view: seat {s['id']} overspent balance={bal} committed={com} spendable={sp}"
                )
        players = Counter(a["player"] for a in pub["auctions"])
        dup = [p for p, n in players.items() if n > 1]
        if dup:
            self.violations.append(f"HTTP view: players nominated/won more than once: {dup}")
        for a in pub["auctions"]:
            if a["status"] == "closed" and not a["winner"]:
                self.violations.append(f"HTTP view: closed lot {a['id']} without a winner")
        # each seat's own private ledger
        for m in self.managers:
            async with self.client(m.cookie) as c:
                r = await c.get(f"/api/auction/rooms/{self.room}/view")
                priv = r.json()["me"]["private"] or {}
            bal, com, sp = priv.get("balance"), priv.get("committed"), priv.get("spendable")
            if bal is not None and (bal < 0 or com > bal or sp < 0):
                self.violations.append(
                    f"HTTP private view: seat {m.seat} balance={bal} committed={com} spendable={sp}"
                )
        # every acknowledged command has a durable receipt with the same outcome
        acked = [x for x in self.cmds if x.status == 200 and not x.replayed]
        sem = asyncio.Semaphore(16)
        clients = {m.idx: self.client(m.cookie) for m in self.managers}
        bad = 0

        async def check(x: Cmd) -> None:
            nonlocal bad
            async with sem:
                st, raw, _ = await self.call(
                    clients[x.manager],
                    "GET",
                    f"/api/auction/rooms/{self.room}/receipts/{x.key}",
                    "verify_receipt",
                )
            if st != 200:
                bad += 1
                self.violations.append(f"acknowledged command lost: key={x.key} receipt={st}")
                return
            rc = json.loads(raw)
            if int(rc["status"]) != 200 or rc.get("revision") != x.revision:
                bad += 1
                self.violations.append(
                    f"receipt disagrees with ack: key={x.key} ack=(200,{x.revision})"
                    f" receipt=({rc['status']},{rc.get('revision')})"
                )

        try:
            await asyncio.gather(*[check(x) for x in acked])
        finally:
            for c in clients.values():
                await c.aclose()
        self.receipts_checked = len(acked)
        self.receipts_bad = bad

    def verify_db(self) -> dict:
        """After a hard kill: fresh Store over the same file."""
        sys.path.insert(0, str(REPO))
        from src.auction import engine
        from src.auction.store import open_store

        out: dict[str, Any] = {}
        st = open_store(self.db_path)
        state, revision, _ = st.load(self.room)
        out["revision"] = revision
        out["status"] = state["status"]
        try:
            engine.check_invariants(state)
            out["engine_invariants"] = "ok"
        except AssertionError as exc:
            out["engine_invariants"] = f"FAILED: {exc}"
            self.violations.append(f"engine invariants: {exc}")
        report = st.verify_room(self.room)
        out["replay_matches"] = report["replay_matches"]
        out["awards_match"] = report["awards_match"]
        if not report["replay_matches"]:
            self.violations.append("command-log replay does not reproduce the room")
        if not report["awards_match"]:
            self.violations.append("awards table disagrees with closed lots")
        seats = []
        for s in state["seats"]:
            bal = engine.balance(state, s["id"])
            com = engine.committed(state, s["id"])
            seats.append((s["id"], s["opening_budget"], bal, com, bal - com))
            if bal < 0 or com > bal:
                self.violations.append(
                    f"DB: seat {s['id']} overspent balance={bal} committed={com}"
                )
        out["seats"] = seats
        closed = [a for a in state["auctions"].values() if a["status"] == "closed"]
        out["lots_total"] = len(state["auctions"])
        out["lots_closed"] = len(closed)
        out["lots_open"] = len(engine.open_auctions(state))
        out["bid_log_len"] = len(state.get("bid_log") or [])
        out["state_json_bytes"] = len(json.dumps(state, sort_keys=True))
        conn = sqlite3.connect(str(self.db_path))
        conn.row_factory = sqlite3.Row
        try:
            dup_awards = conn.execute(
                "SELECT player_id, COUNT(*) n FROM awards WHERE room_id=? GROUP BY player_id HAVING n>1",
                (self.room,),
            ).fetchall()
            if dup_awards:
                self.violations.append(f"duplicate winners: {[r['player_id'] for r in dup_awards]}")
            out["awards"] = conn.execute(
                "SELECT COUNT(*) FROM awards WHERE room_id=?", (self.room,)
            ).fetchone()[0]
            # Winners per settled player from the state itself.
            per_player = Counter(a["player"] for a in closed)
            if any(n > 1 for n in per_player.values()):
                self.violations.append("a player was settled more than once")
            idem = {
                (r["user_id"], r["key"]): r
                for r in conn.execute(
                    "SELECT user_id, key, revision, status, result_json, created_at FROM idempotency WHERE room_id=?",
                    (self.room,),
                )
            }
            dup_keys = conn.execute(
                "SELECT user_id, key, COUNT(*) n FROM idempotency WHERE room_id=? GROUP BY user_id, key HAVING n>1",
                (self.room,),
            ).fetchall()
            if dup_keys:
                self.violations.append(f"duplicate idempotency rows: {len(dup_keys)}")
            human_cmds = conn.execute(
                "SELECT revision, actor_user_id, kind, created_at FROM commands WHERE room_id=? AND actor_user_id IS NOT NULL",
                (self.room,),
            ).fetchall()
        finally:
            conn.close()
        out["idempotency_rows"] = len(idem)
        out["human_command_rows"] = len(human_cmds)
        # (1) every client-acknowledged 200 survived the hard kill, same revision.
        lost = 0
        by_uid = {m.idx: m.user_id for m in self.managers}
        max_acked = -1
        for x in self.cmds:
            if x.status is None:
                continue
            row = idem.get((by_uid[x.manager], x.key))
            if x.status == 200:
                max_acked = max(max_acked, x.revision or -1)
                if row is None or int(row["status"]) != 200 or row["revision"] != x.revision:
                    lost += 1
                    if lost <= 10:
                        self.violations.append(
                            f"DB: acknowledged action missing/changed key={x.key} row="
                            f"{None if row is None else (row['status'], row['revision'])}"
                        )
            elif (
                row is not None and int(row["status"]) == 200 and x.error != "idempotency_conflict"
            ):
                self.violations.append(
                    f"DB: client saw {x.status} but receipt says 200 key={x.key}"
                )
        out["lost_acknowledged"] = lost
        if revision < max_acked:
            self.violations.append(f"DB revision {revision} < highest acknowledged {max_acked}")
        # (2) every human command row was committed by exactly one accepted
        # receipt.  Store.execute stamps the SAME now_real on the command row and
        # its idempotency row, so (user, revision, created_at) is an exact join.
        # Note a receipt saying {"noop": true} can still own a command row: the
        # engine settles lots that fell due at the command's own server time in
        # the same transaction, so the revision advances even though the bid
        # itself changed nothing.  Joining on revision alone miscounts both that
        # case and later no-op resubmissions that record the unchanged revision.
        # On Windows + Python < 3.13 time.time() ticks at ~15.6 ms, so a later
        # no-op resubmission by the same user can share that (revision,
        # now_real) exactly: the owner is the one NON-no-op receipt, or a lone
        # no-op receipt (the settle-due case above).
        real_by_commit: dict[tuple[int, int, float], list[str]] = defaultdict(list)
        noop_by_commit: dict[tuple[int, int, float], list[str]] = defaultdict(list)
        noop_receipts = 0
        for (uid, key), r in idem.items():
            if int(r["status"]) != 200:
                continue
            try:
                res = json.loads(r["result_json"]) or {}
            except (TypeError, ValueError):
                res = {}
            k = (uid, r["revision"], float(r["created_at"]))
            if isinstance(res, dict) and res.get("noop"):
                noop_receipts += 1
                noop_by_commit[k].append(key)
            else:
                real_by_commit[k].append(key)
        out["noop_receipts"] = noop_receipts
        orphan = []
        for c in human_cmds:
            k = (c["actor_user_id"], c["revision"], float(c["created_at"]))
            real = real_by_commit.get(k, [])
            noop = noop_by_commit.get(k, [])
            if not (len(real) == 1 or (not real and len(noop) == 1)):
                orphan.append((c["revision"], c["actor_user_id"], c["kind"], real + noop))
        out["command_rows_without_single_receipt"] = len(orphan)
        if orphan:
            self.violations.append(
                f"{len(orphan)} applied command rows are not owned by exactly one accepted"
                f" receipt; e.g. (revision, user, kind, keys) {orphan[:5]}"
            )
        # (3) every accepted, non-noop bid / nomination / withdrawal changes the
        # room (the engine appends to bid_log or flips a bid), so each must be in
        # the command log at its acknowledged revision, by its own user and kind.
        cmd_rows = {(c["actor_user_id"], c["revision"]): c["kind"] for c in human_cmds}
        missing = 0
        for x in self.cmds:
            if (
                x.status == 200
                and not x.replayed
                and not x.noop
                and x.kind in ("bid", "nominate", "withdraw")
                and cmd_rows.get((by_uid[x.manager], x.revision)) != x.kind
            ):
                missing += 1
        out["accepted_actions_missing_from_log"] = missing
        if missing:
            self.violations.append(f"{missing} accepted actions are not in the command log")
        return out

    def scan_log(self) -> dict:
        try:
            text = self.log_path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            return {}
        return {
            "database is locked": text.count("database is locked"),
            "OperationalError": text.count("OperationalError"),
            "Traceback": text.count("Traceback"),
            "ERROR lines": sum(
                1 for ln in text.splitlines() if " ERROR" in ln or ln.startswith("ERROR")
            ),
            "HTTP 5xx access lines": len(re.findall(r'" 5\d\d', text)),
        }

