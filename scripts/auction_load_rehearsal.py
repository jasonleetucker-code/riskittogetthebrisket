    def propagation(self) -> dict:
        # Per manager: merged observations (any tab), running max.
        series: dict[int, tuple[list[float], list[int]]] = {}
        for m in self.managers:
            pts = sorted(p for (mi, _), obs in self.obs.items() if mi == m.idx for p in obs)
            ts, rm = [], []
            best = -1
            for t, r in pts:
                best = max(best, r)
                ts.append(t)
                rm.append(best)
            series[m.idx] = (ts, rm)
        per_client: list[float] = []
        all_clients: list[float] = []
        missed_pairs = 0
        missed_by_seat: Counter = Counter()
        acks = [
            x
            for x in self.cmds
            if x.status == 200
            and not x.replayed
            and not x.noop
            and x.revision is not None
            and x.t_ack is not None
            and x.t_ack <= self.t_load1
        ]
        for x in acks:
            worst = 0.0
            complete = True
            for m in self.managers:
                if m.idx == x.manager:
                    continue
                ts, rm = series[m.idx]
                i = bisect.bisect_left(rm, x.revision)
                if i >= len(rm):
                    missed_pairs += 1
                    missed_by_seat[m.seat] += 1
                    complete = False
                    continue
                d = max(0.0, ts[i] - x.t_ack)
                per_client.append(d)
                worst = max(worst, d)
            if complete:
                all_clients.append(worst)
        return {
            "acks": len(acks),
            "per_client": per_client,
            "all_clients": all_clients,
            "missed_pairs": missed_pairs,
            "missed_by_seat": dict(missed_by_seat),
        }

    def timeline(self) -> list[dict]:
        rows = []
        width = 10.0
        span = self.t_load1 - self.t_load0
        nb = max(1, math.ceil(span / width))
        bids = [x for x in self.cmds if x.kind == "bid" and x.t_ack is not None]
        for b in range(nb):
            lo, hi = self.t_load0 + b * width, self.t_load0 + (b + 1) * width
            bl = [x.t_ack - x.t_send for x in bids if lo <= x.t_send < hi]
            hl = [lat for t, lat in self.health if lo <= t < hi and lat is not None]
            cpu = None
            ss = [(t, s) for t, s in self.proc_samples if lo <= t < hi]
            if len(ss) >= 2 and ss[0][1].get("cpu_s") is not None:
                cpu = 100.0 * (ss[-1][1]["cpu_s"] - ss[0][1]["cpu_s"]) / (ss[-1][0] - ss[0][0])
            rows.append(
                {
                    "t": f"{b * width:>4.0f}-{(b + 1) * width:<4.0f}",
                    "cmds": sum(1 for x in self.cmds if lo <= x.t_send < hi),
                    "bid_p95": pct(bl, 0.95),
                    "health_max": max(hl) if hl else None,
                    "cpu_pct": cpu,
                }
            )
        return rows


