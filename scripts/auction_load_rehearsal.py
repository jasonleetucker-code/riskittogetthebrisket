    async def reconnect_loop(self) -> None:
        rng = random.Random(self.a.seed * 13)
        while not self.stop_load.is_set():
            await asyncio.sleep(self.a.reconnect_every)
            if self.stop_load.is_set():
                break
            m = rng.choice(self.managers)
            tab = rng.randrange(m.tab_count)
            task = m.tab_tasks.get(tab)
            if task is not None:
                task.cancel()
                try:
                    await task
                except (asyncio.CancelledError, Exception):  # noqa: BLE001
                    pass
            t0 = now()
            m.tab_tasks[tab] = asyncio.create_task(self.tab_loop(m, tab, reconnect_t0=t0))

