"""12-manager load rehearsal for the rookie auction room — LOCAL ONLY.

What it does
------------
Spawns a throwaway uvicorn process on an ephemeral ``127.0.0.1`` port with a
temporary auction store (``RISKIT_AUCTION_DB``), creates a MOCK room with 12
human-account seats (the site-owner commissioner plus 11 accounts created
through the room's own invite flow — random per-run passwords, no real
credentials), starts it, opens 12 lots, and then drives it for ``--duration``
seconds with:

* 12 manager clients, each holding 2-3 "tabs" that run their own
  ``GET /view?after=<rev>&wait=25`` long-poll loops (mirroring
  ``frontend/lib/auction-client.js``: first snapshot, then long-poll, drop
  responses older than the revision held);
* a concurrent bidding burst per manager (random proxy maxima, raises, $0
  bids, withdrawals, nominations, deliberate idempotent replays and
  idempotency conflicts), with the frontend's unknown-outcome retry rule
  (receipt lookup, same Idempotency-Key);
* concurrent ``GET /advice-context`` (Perfect Draft) and notification-state /
  inbox reads;
* a reconnect chaos loop (kill one tab's poll mid-flight, restart it);
* commissioner mock-clock jumps so lots settle during the run;
* an ``/api/health`` ping loop (event-loop responsiveness) and a server
  process sampler (CPU, RSS, handles/FDs).

Afterwards it verifies invariants from a FRESH read — over HTTP, and again
directly from the SQLite file after the server is hard-killed (crash-style
stop): no seat overspent (committed <= balance, spendable >= 0), one winner
per settled player, no duplicate idempotency operation, no lost acknowledged
action, replay of the command log reproduces the room.

What it does NOT measure
------------------------
The app under test is a SHIM: the real ``src/auction`` router, store, engine
and runtime, mounted on a bare FastAPI app with GZip (as production), plus a
stub ``server`` module (site-owner session check against a random per-run
token, the contract loaded from a local export).  It does NOT load the rest
of ``server.py`` (scrapes, other routes, their middleware and memory), and
there is no nginx in front.  Production sits behind nginx (``/api/``
buffering, a proxy read timeout) on a different host.  Treat the numbers as
the auction code path's own capacity on this machine, not a production SLO.

The shim also wraps ``Store.write`` / ``Store.read`` / the store's writer
lock with timers (measurement only, inside the throwaway process) so SQLite
lock waits and transaction hold times can be reported.  No ``src/`` file is
modified.

Usage
-----
    python scripts/auction_load_rehearsal.py                 # 120 s default
    python scripts/auction_load_rehearsal.py --duration 60 --json-out out.json

Exit codes: 0 = invariants held; 1 = invariant violation; 2 = harness/setup
failure; 3 = a performance target missed (only with ``--strict-targets``).
"""

