    async def _setup_cmd(self, c, body: dict) -> None:
        r = await c.post(
            f"/api/auction/rooms/{self.room}/commands",
            json=body,
            headers={"Idempotency-Key": new_key()},
        )
        if r.status_code != 200:
            raise RuntimeError(f"{body['kind']} failed: {r.status_code} {r.text[:200]}")

    # -- commands (mirrors frontend sendCommand) --------------------------------

    async def command(self, m: Manager, c, body: dict, purpose: str, key: str | None = None) -> Cmd:
        rec = Cmd(m.idx, body["kind"], purpose, key or new_key(), body, t_send=now())
        path = f"/api/auction/rooms/{self.room}/commands"
        for i in range(3):
            rec.attempts += 1
            st, raw, terr = await self.call(
                c, "POST", path, "command", json=body, headers={"Idempotency-Key": rec.key}
            )
            if st is not None and st < 502:
                rec.status = st
                self._fill(rec, raw)
                break
            rec.transport_error = terr or f"http_{st}"
            # Unknown outcome: ask whether it committed before re-sending.
            self.receipt_lookups += 1
            rst, rraw, _ = await self.call(
                c, "GET", f"/api/auction/rooms/{self.room}/receipts/{rec.key}", "receipt"
            )
            if rst == 200:
                receipt = json.loads(rraw)
                rec.status = int(receipt["status"])
                rec.revision = receipt.get("revision")
                res = receipt.get("result") or {}
                rec.noop = bool(res.get("noop"))
                rec.error = res.get("error")
                rec.via_receipt = True
                break
            if i < 2:
                self.retries += 1
                await asyncio.sleep(0.4 * (i + 1))
        rec.t_ack = now()
        self.cmds.append(rec)
        return rec

    @staticmethod
    def _fill(rec: Cmd, raw: bytes) -> None:
        try:
            js = json.loads(raw)
        except ValueError:
            return
        rec.revision = js.get("revision")
        rec.replayed = bool(js.get("replayed"))
        rec.noop = bool(js.get("noop"))
        rec.error = js.get("error")

    # -- tabs (long-poll clients) -------------------------------------------------

    def _observe(self, m: Manager, tab: int, raw: bytes, prev: int) -> int:
        t = now()
        mt = _REV_RE.match(raw[:40])
        if mt:
            rev = int(mt.group(1))
        else:
            try:
                rev = int(json.loads(raw)["revision"])
            except (ValueError, KeyError, TypeError):
                return prev
        self.obs[(m.idx, tab)].append((t, rev))
        if rev < prev:
            self.out_of_order += 1  # dropped, exactly like the frontend
            return prev
        if rev == prev:
            self.poll_unchanged += 1
        if rev > m.latest_rev:
            try:
                view = json.loads(raw)
            except ValueError:
                return rev
            evs = view.get("events") or []
            if m.parsed_rev >= 0 and len(evs) >= EVENT_LIMIT:
                oldest = min(int(e["revision"]) for e in evs)
                if oldest > m.parsed_rev + 1:
                    m.event_gaps += 1
            m.latest = view
            m.latest_rev = rev
            m.parsed_rev = rev
        return rev

    async def tab_loop(self, m: Manager, tab: int, reconnect_t0: float | None = None) -> None:
        c = self.client(m.cookie)
        rev = -1
        view_path = f"/api/auction/rooms/{self.room}/view"
        try:
            while not self.stop_polls.is_set():
                st, raw, _ = await self.call(c, "GET", view_path, "view_initial")
                if st == 200:
                    rev = self._observe(m, tab, raw, rev)
                    break
                await asyncio.sleep(2.0)
            if reconnect_t0 is not None:
                self.reconnects.append(now() - reconnect_t0)
            failures = 0
            wait = self.a.poll_wait
            while not self.stop_polls.is_set():
                st, raw, _ = await self.call(
                    c,
                    "GET",
                    f"{view_path}?after={rev}&wait={wait}",
                    "view_poll",
                    timeout=wait + 20,
                )
                if st == 200:
                    rev = self._observe(m, tab, raw, rev)
                    failures = 0
                else:
                    failures += 1
                    await asyncio.sleep(min(10.0, 1.0 * 2 ** min(failures, 4)))
        finally:
            await c.aclose()

    # -- load actors --------------------------------------------------------------

    def _in_burst(self) -> bool:
        if self.a.burst_every <= 0:
            return False
        el = now() - self.t_load0
        return (el % self.a.burst_every) < self.a.burst_seconds

    def _choose(self, m: Manager, rng: random.Random) -> tuple[dict, str] | None:
        v = m.latest
        if not v:
            return None
        pub = v.get("public") or {}
        priv = (v.get("me") or {}).get("private") or {}
        auctions = pub.get("auctions") or []
        taken = {a["player"] for a in auctions}
        avail = [p for p in self.pool_ids if p not in taken]
        open_lots = [a for a in auctions if a["status"] == "open"]
        balance = int(priv.get("balance") or 0)
        mine = {b["auction"]: b for b in priv.get("my_bids") or []}
        if priv.get("on_clock") and avail and rng.random() < 0.85:
            return {"kind": "nominate", "player": rng.choice(avail)}, "nominate_on_clock"
        r = rng.random()
        if not open_lots or r < 0.03:
            if not avail:
                return None
            return {"kind": "nominate", "player": rng.choice(avail)}, "nominate_off_clock"
        if rng.random() < 0.03:  # deliberately unaffordable (expected 409 over_balance)
            lot = rng.choice(open_lots)
            return {
                "kind": "bid",
                "auction": lot["id"],
                "max": balance + rng.randint(1, 20),
            }, "over_balance"
        if r < 0.10:
            zero = [a for a in open_lots if int(a["price"]) == 0 and a.get("leader") != m.seat]
            if zero:
                return {"kind": "bid", "auction": rng.choice(zero)["id"], "max": 0}, "zero_bid"
        # Managers bid where they can afford to; a few hot lots draw most action.
        afford = [a for a in open_lots if int(a["price"]) + 1 <= balance]
        if not afford:
            return None
        lot = rng.choice(afford[:4]) if rng.random() < 0.5 else rng.choice(afford)
        price = int(lot["price"])
        leading = lot.get("leader") == m.seat
        if r < 0.35:
            if leading and lot["id"] in mine:
                cur = int(mine[lot["id"]]["max"])
                if cur >= balance:
                    return None
                return {
                    "kind": "bid",
                    "auction": lot["id"],
                    "max": min(balance, cur + rng.randint(1, 15)),
                }, "leader_raise"
            return {"kind": "bid", "auction": lot["id"], "max": price + 1}, "min_raise"
        if r < 0.40:
            cand = [a for a in open_lots if a["id"] in mine and a.get("leader") != m.seat]
            if cand:
                return {"kind": "withdraw", "auction": rng.choice(cand)["id"]}, "withdraw"
        top = max(price + 1, int(balance * rng.random()))
        return {
            "kind": "bid",
            "auction": lot["id"],
            "max": rng.randint(price + 1, max(price + 1, top)),
        }, "proxy"

    async def bidder(self, m: Manager, n: int) -> None:
        rng = random.Random(self.a.seed * 1000 + m.idx * 10 + n)
        c = self.client(m.cookie)
        try:
            while not self.stop_load.is_set():
                mean = self.a.burst_interval if self._in_burst() else self.a.bid_interval
                await asyncio.sleep(rng.expovariate(1.0 / mean))
                if self.stop_load.is_set():
                    break
                choice = self._choose(m, rng)
                if choice is None:
                    continue
                body, purpose = choice
                rec = await self.command(m, c, body, purpose)
                if rec.status == 200 and not rec.replayed:
                    roll = rng.random()
                    if roll < self.a.replay_rate:
                        again = await self.command(m, c, body, "replay_same_key", key=rec.key)
                        ok = (
                            again.status == 200
                            and again.replayed
                            and again.revision == rec.revision
                        )
                        self.replay_checks["replay_ok" if ok else "replay_MISMATCH"] += 1
                        if not ok:
                            self.violations.append(
                                f"idempotent replay mismatch key={rec.key} first=(200,{rec.revision})"
                                f" again=({again.status},{again.revision},replayed={again.replayed})"
                            )
                    elif roll < self.a.replay_rate + self.a.conflict_rate and body["kind"] == "bid":
                        changed = {**body, "max": int(body["max"]) + 1}
                        again = await self.command(m, c, changed, "conflict_same_key", key=rec.key)
                        ok = again.status == 409 and again.error == "idempotency_conflict"
                        self.replay_checks["conflict_ok" if ok else "conflict_MISMATCH"] += 1
                        if not ok:
                            self.violations.append(
                                f"idempotency conflict not refused key={rec.key}"
                                f" got=({again.status},{again.error})"
                            )
        finally:
            await c.aclose()

